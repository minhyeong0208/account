  `INTERESTRATE` decimal(5,2) NOT NULL COMMENT '금리 (예: 2.75)',
  `EXPIRATIONDATE` datetime NOT NULL COMMENT '만기일',
  `STATUS` varchar(10) DEFAULT NULL,
  `BANKNAME` varchar(100) DEFAULT NULL COMMENT '은행명',
  `MEMO` varchar(1000) DEFAULT NULL COMMENT '메모',
  `REGID` varchar(50) DEFAULT NULL COMMENT '등록자ID',
  `REGDATE` datetime DEFAULT NULL COMMENT '등록일시',
  `MODID` varchar(50) DEFAULT NULL COMMENT '수정자ID',
  `MODDATE` datetime DEFAULT NULL COMMENT '수정일시',
  PRIMARY KEY (`SAVINGSID`,`USERID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='적금';

CREATE TABLE `acc_savings_history` (
