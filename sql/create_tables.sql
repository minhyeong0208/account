CREATE TABLE `acc_account` (
  `USERID` varchar(50) NOT NULL COMMENT '사용자ID',
  `ACCOUNTID` decimal(10,0) NOT NULL COMMENT '계좌ID',
  `BANKNM` varchar(50) NOT NULL COMMENT '은행명',
  `ACCOUNTNUM` varchar(30) DEFAULT NULL COMMENT '계좌번호',
  `INITMONEY` decimal(10,0) DEFAULT 0 COMMENT '초기잔액',
  `REGID` varchar(50) DEFAULT NULL COMMENT '등록자ID',
  `REGDATE` datetime DEFAULT NULL COMMENT '등록일시',
  `MODID` varchar(50) DEFAULT NULL COMMENT '수정자ID',
  `MODDATE` datetime DEFAULT NULL COMMENT '수정일시',
  PRIMARY KEY (`USERID`,`ACCOUNTID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='계좌';

CREATE TABLE `acc_category` (
  `USERID` varchar(50) NOT NULL COMMENT '사용자ID',
  `CATEGORYID` decimal(10,0) NOT NULL COMMENT '항목ID',
  `USAGENM` varchar(100) DEFAULT NULL COMMENT '사용처',
  `CATEGORYNM` varchar(50) NOT NULL COMMENT '항목명',
  `CATEGORYDETAILNM` varchar(100) DEFAULT NULL COMMENT '세부항목명',
  `CLASSIFICATION` varchar(10) NOT NULL COMMENT '분류구분 (INCOME/EXPENSE)',
  `REGID` varchar(50) DEFAULT NULL COMMENT '등록자ID',
  `REGDATE` datetime DEFAULT NULL COMMENT '등록일시',
  `MODID` varchar(50) DEFAULT NULL COMMENT '수정자ID',
  `MODDATE` datetime DEFAULT NULL COMMENT '수정일시',
  PRIMARY KEY (`USERID`,`CATEGORYID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='항목';

CREATE TABLE `acc_history` (
  `ACCOUNTID` varchar(50) NOT NULL COMMENT '계좌ID',
  `USERID` varchar(50) NOT NULL COMMENT '사용자ID',
  `TRANID` decimal(10,0) NOT NULL COMMENT '입출금내역ID',
  `TRANTYPE` varchar(10) DEFAULT NULL COMMENT '거래유형 (INCOME/EXPENSE)',
  `TRANAMOUNT` decimal(10,0) DEFAULT NULL COMMENT '거래금액',
  `TRANAFTAMOUNT` decimal(10,0) DEFAULT NULL COMMENT '거래후잔액',
  `DESCRIPTION` varchar(200) DEFAULT NULL COMMENT '적요',
  `CATEGORYID` varchar(50) DEFAULT NULL COMMENT '항목ID',
  `TRANDATE` datetime DEFAULT NULL COMMENT '거래일시',
  `TRANTIME` varchar(8) DEFAULT NULL,
  `DELYN` varchar(1) DEFAULT 'N' COMMENT '삭제여부 (Y/N)',
  `REGID` varchar(50) DEFAULT NULL COMMENT '등록자ID',
  `REGDATE` datetime DEFAULT current_timestamp() COMMENT '등록일시',
  `MODID` varchar(50) DEFAULT NULL COMMENT '수정자ID',
  `MODDATE` datetime DEFAULT NULL COMMENT '수정일시',
  PRIMARY KEY (`ACCOUNTID`,`USERID`,`TRANID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='입출금내역';

CREATE TABLE `acc_savings` (
  `SAVINGSID` varchar(50) NOT NULL COMMENT '적금ID',
  `USERID` varchar(50) NOT NULL COMMENT '사용자ID',
  `SAVINGNM` varchar(100) NOT NULL COMMENT '적금명',
